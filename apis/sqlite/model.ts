/**
 * El model de dades del portal: les taules de SQLite, els seus camps i com es
 * relacionen. És l'única font: `bd.ts` en crea les taules (i hi afegeix les
 * columnes que falten), i `consulta.ts` en treu les relacions per resoldre els
 * camps amb punt (`client.nom_comercial`) i els filtres que travessen taules.
 *
 * Cada taula té, a més dels camps d'aquí, la clau `id` (un UUID en text).
 * `date_created` i `date_updated` els posa el motor sol quan hi són.
 */

export type TipusCamp = "text" | "json" | "enter" | "decimal" | "boolea" | "data" | "instant" | "uuid";

export type DefinicioCamp = {
  tipus: TipusCamp;
  /** Many-to-one: la taula a què apunta aquest camp. */
  m2o?: string;
  /** Què passa si s'esborra la fila a què apunta. Per defecte, el camp es buida. */
  enEsborrar?: "CASCADE";
  perDefecte?: string | number | boolean;
  unic?: boolean;
  index?: boolean;
};

export type DefinicioTaula = {
  camps: Record<string, DefinicioCamp>;
  /** One-to-many: un àlies que porta les files d'una altra taula que apunten a aquesta. */
  o2m?: Record<string, { colleccio: string; camp: string }>;
  /** Una sola fila: es llegeix i es desa sense id. */
  singleton?: boolean;
};

